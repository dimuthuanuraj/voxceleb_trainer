"""Build the full report package: HTML + Markdown + PDF + individual figures.

Layout produced:

    data/datasets_reports/
    ├── README.md                       index
    ├── <dataset>/
    │   ├── <dataset>.html              same content as the published artifact
    │   ├── <dataset>.md
    │   ├── <dataset>.pdf
    │   └── figures/NN_<key>.png|.svg   every figure, individually
    └── comparison/
        ├── comparison.{html,md,pdf}
        └── figures/

All three formats come from one block list per report (tools/qc_report_model.py),
so they cannot disagree.

Usage:
    python tools/build_report_package.py
"""

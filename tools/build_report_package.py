def comparison_blocks(ds, figs):
    names = [d["name"] for d in ds]
    spk, hours, utts, dpr, nmi, sil, mde, eer, eta = ([] for _ in range(9))
    for d in ds:
        L2 = d["qc"].get("L2_distribution", {})
        spk.append(speaker_count(d))
        hours.append(sum(v["hours"] for v in L2.values()))
        utts.append(sum(v["utterances"] for v in L2.values()))
        a = d["audit"]
        dpr.append(a.get("separability_dprime", 0))
        nmi.append(a.get("clustering_vs_labels", {}).get("fixed_k", {}).get("NMI", 0))
        sil.append(a.get("silhouette", {}).get("mean", 0))
        eta.append(d["sig"].get("speaker_confound_anova", {})
                   .get("snr_db", {}).get("eta_squared", 0))
        bm, be = None, None
        for l, v in (d["power"] or {}).items():
            m = v["MDE_pct"]["rho_0.7_typical_paired"]
            if bm is None or m < bm:
                bm, be = m, v["EER_avg"]
        mde.append(bm if bm is not None else float("nan"))
        eer.append(be if be is not None else float("nan"))

    B = []
    valid = [m for m in mde if m == m]
    B.append(("kpis", [
        ("Corpora measured", "6", "338k utterances", ""),
        ("Total speakers", f"{sum(spk):,}", "after identity corrections", ""),
        ("Best MDE", f"{min(valid):.2f} pp" if valid else "—",
         "smallest resolvable effect", "warn"),
        ("Channel probe", f"{SHIFT.get('channel_probe', {}).get('accuracy', 0)*100:.1f} %",
         f"chance {SHIFT.get('channel_probe', {}).get('chance', 0)*100:.0f} %", "bad"),
    ]))

    B.append(("h2", "01", "The master table"))
    rows = []
    for i, d in enumerate(ds):
        t = TITLES.get(d["name"], (d["name"], "", ""))
        rows.append([d["name"], t[1], f"{spk[i]:,}", f"{utts[i]:,}",
                     f"{hours[i]:.1f}", f"{dpr[i]:.2f}", f"{nmi[i]:.3f}",
                     f"{sil[i]:.3f}", f"{eta[i]:.2f}", f"{eer[i]:.2f}",
                     f"{mde[i]:.2f}"])
    B.append(("table", ["Corpus", "Lang", "Speakers", "Utts", "Hours", "d'", "NMI",
                        "Silhouette", "eta2(SNR)", "EER %", "MDE pp"], rows))
    B.append(("endsection",))

    B.append(("h2", "02", "Can any corpus resolve an ablation effect?"))
    B.append(("dek", "The question the whole assessment exists to answer."))
    F.RETURN_FIG = True
    k = figs.add_figure("mde", F.mde_chart(names, eer, mde))
    F.RETURN_FIG = False
    B.append(("fig", k, "Minimum detectable effect from a speaker-clustered "
                        "bootstrap at rho=0.7. Anything right of the red line "
                        "cannot support a defensible ranking of feature variants."))
    B.append(("math", "Minimum detectable effect",
              r"MDE=(z_{1-\alpha/2}+z_{1-\beta})\,SE\sqrt{2(1-\rho)}"
              r",\qquad \alpha=0.05,\ 1-\beta=0.8"))
    bi = int(np.nanargmin(mde))
    bm = mde[bi]
    if bm <= .2:
        B.append(("callout", "", f"{names[bi]} is adequately powered",
                  f"at MDE {bm:.2f} pp. The ablation can proceed as designed."))
    elif bm <= .5:
        B.append(("callout", "warn",
                  f"{names[bi]} is the only corpus close to usable power —",
                  f"MDE {bm:.2f} pp, just above the 0.2 pp target and well inside "
                  f"the 0.5 pp limit. Large feature effects are rankable; a wide "
                  f"grid of small ones is not. Narrow the ablation to fewer, bolder "
                  f"conditions on {names[bi]}, and treat every other corpus as "
                  f"confirmatory."))
    else:
        B.append(("callout", "bad", "No corpus reaches even the 0.5 pp limit.",
                  "That is the 'more speakers before more experiments' case."))
    B.append(("callout", "", "Trials do not buy power; speakers do.",
              f"Kathbath supplies 50,000 official trials and lands at MDE "
              f"{max(valid):.2f} pp on 20 speakers, while {names[bi]} reaches "
              f"{bm:.2f} pp from 12,000 trials over {spk[bi]}. Sampling more pairs "
              f"from the same voices re-uses information already in the corpus."))
    B.append(("endsection",))

    B.append(("h2", "03", "Scale and shape"))
    F.RETURN_FIG = True
    k1 = figs.add_figure("scale", F.scatter_speakers_hours(names, spk, hours, mde))
    dur = []
    for d in ds:
        L2 = d["qc"].get("L2_distribution", {})
        if L2:
            v = list(L2.values())[0]["duration_histogram"]
            dur.append((d["name"], v["bin_edges_s"], v["counts"]))
    k2 = figs.add_figure("durations", F.duration_overlay(dur)) if dur else None
    F.RETURN_FIG = False
    B.append(("fig", k1, "Speakers against hours, both log. Marker area encodes "
                         "1/MDE (clipped to a legible range), so bigger means more "
                         "statistical power — and the vertical spread shows how "
                         "little hours buy compared with speakers."))
    if k2:
        B.append(("fig", k2, "Duration profiles. Mass below 2 s costs EER for "
                             "reasons unrelated to the speakers."))
    B.append(("endsection",))

    B.append(("h2", "04", "Label quality and separability"))
    F.RETURN_FIG = True
    k3 = figs.add_figure("dprime", F.compare_bars(names, dpr, "d'",
                                                  "Speaker separability",
                                                  thresholds=(4.0, 3.0)))
    k4 = figs.add_figure("nmi", F.compare_bars(names, nmi, "NMI",
                                                "Clustering vs given labels",
                                                thresholds=(.95, .90), fmt="{:.3f}"))
    F.RETURN_FIG = False
    B.append(("fig", k3, "d' between within- and between-speaker cosine "
                         "distributions."))
    B.append(("fig", k4, "Agreement between agglomerative clustering and the "
                         "distributed speaker labels."))
    B.append(("math", "Separability and agreement",
              r"d'=\frac{\mu_w-\mu_b}{\sqrt{(\sigma_w^2+\sigma_b^2)/2}}"
              r"\qquad NMI=\frac{2I(U;V)}{H(U)+H(V)}"))
    B.append(("endsection",))

    B.append(("h2", "05", "Is channel acting as identity?"))
    F.RETURN_FIG = True
    k5 = figs.add_figure("eta_snr", F.compare_bars(
        names, eta, "eta^2 of SNR across speakers", "Channel/speaker confound",
        thresholds=(.25, .5), higher_is_better=False, fmt="{:.2f}"))
    F.RETURN_FIG = False
    B.append(("fig", k5, "Fraction of the variance in per-utterance SNR explained "
                         "by speaker identity."))
    cp = SHIFT.get("channel_probe", {})
    if cp:
        B.append(("callout", "bad",
                  f"Corpus-of-origin is {cp['accuracy']*100:.1f} % linearly "
                  f"decodable from the speaker embedding",
                  f"(chance {cp['chance']*100:.0f} %). The embedding space encodes "
                  f"recording channel as strongly as it encodes anything "
                  f"corpus-independent, so cross-corpus comparisons are partly "
                  f"comparisons of microphones. This is the single strongest "
                  f"argument against quoting one corpus's absolute EER as a "
                  f"performance claim."))
    if SHIFT.get("frechet"):
        rows = [[k, f"{v:.3f}", f"{SHIFT['centroid_cosine'].get(k, 0):.3f}"]
                for k, v in SHIFT["frechet"].items()]
        B.append(("table", ["Corpus pair", "Frechet distance", "Centroid cosine"],
                  rows))
        B.append(("math", "Frechet distance between embedding distributions",
                  r"d^2=\|\mu_A-\mu_B\|^2+tr\left(\Sigma_A+\Sigma_B"
                  r"-2(\Sigma_A\Sigma_B)^{1/2}\right)"))
    B.append(("endsection",))

    tsne_items, umap_items = [], []
    for d in ds:
        if d["proj"] is not None:
            p = d["proj"]
            tsne_items.append((d["name"], p["tsne"], p["spk"]))
            if len(p["umap"]):
                umap_items.append((d["name"], p["umap"], p["spk"]))
    if tsne_items:
        B.append(("h2", "06", "Embedding space, side by side"))
        B.append(("dek", "Same protocol for every corpus: 14 speakers with at least "
                         "8 utterances, cosine metric, identical seed."))
        F.RETURN_FIG = True
        kt = figs.add_figure("grid_tsne", F.grid_projections(tsne_items, "t-SNE"))
        B.append(("fig", kt, "t-SNE. Tight, separated colour groups mean clean "
                             "labels and an easy corpus."))
        if umap_items:
            ku = figs.add_figure("grid_umap", F.grid_projections(umap_items, "UMAP"))
            B.append(("fig", ku, "UMAP on the same points. Structure appearing in "
                                 "both views is real."))
        F.RETURN_FIG = False
        B.append(("endsection",))

    meta = {
        "title": "Cross-dataset comparison — SL_SPV QC",
        "eyebrow": "SL_SPV / cross-dataset comparison",
        "h1": "Five Sinhala / Tamil corpora, measured side by side",
        "sub": "Layers 0-6 of the quality assessment, run end to end on every built "
               "corpus. One decision comes out of it: whether the feature ablation "
               "is worth running yet.",
        "byline": ["2026-08-10", "ECAPA-TDNN / cosine",
                   "speaker-clustered bootstrap B=1000"],
        "running_head": "Cross-dataset comparison — SL_SPV QC",
        "footer": FOOTER,
    }
    return meta, B



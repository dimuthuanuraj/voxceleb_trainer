def write_report(name, meta, blocks, figs, out_dir):
    html = M.render_html(meta, blocks, figs, CSS)
    with open(os.path.join(out_dir, f"{name}.html"), "w", encoding="utf-8") as fh:
        fh.write(html)
    md = M.render_md(meta, blocks, figs)
    with open(os.path.join(out_dir, f"{name}.md"), "w", encoding="utf-8") as fh:
        fh.write(md)
    M.render_pdf(meta, blocks, figs, os.path.join(out_dir, f"{name}.pdf"))
    n_png = len([f for f in os.listdir(figs.dir) if f.endswith(".png")])
    n_svg = len([f for f in os.listdir(figs.dir) if f.endswith(".svg")])
    print(f"[pkg] {name}: html+md+pdf, {n_png} png / {n_svg} svg figures")


def main():
    os.makedirs(OUT, exist_ok=True)
    ds = []
    for n in ORDER:
        if os.path.isdir(os.path.join(DATA, n)):
            d = collect(n)
            if d["qc"]:
                ds.append(d)

    index = ["# Dataset quality reports", "",
             "Layers 0-6 of the quality assessment, one folder per corpus. Each "
             "folder holds the same report as HTML, Markdown and PDF, plus every "
             "figure as an individual PNG and SVG under `figures/`.", "",
             "| Report | HTML | Markdown | PDF | Figures |", "|---|---|---|---|---|"]

    for d in ds:
        out_dir = os.path.join(OUT, d["name"])
        os.makedirs(out_dir, exist_ok=True)
        figs = M.Figures(out_dir)
        meta, blocks = dataset_blocks(d, figs)
        write_report(d["name"], meta, blocks, figs, out_dir)
        nf = len([f for f in os.listdir(figs.dir) if f.endswith(".png")])
        index.append(f"| {d['name']} | [html]({d['name']}/{d['name']}.html) | "
                     f"[md]({d['name']}/{d['name']}.md) | "
                     f"[pdf]({d['name']}/{d['name']}.pdf) | {nf} |")

    cdir = os.path.join(OUT, "comparison")
    os.makedirs(cdir, exist_ok=True)
    cfigs = M.Figures(cdir)
    cmeta, cblocks = comparison_blocks(ds, cfigs)
    write_report("comparison", cmeta, cblocks, cfigs, cdir)
    nf = len([f for f in os.listdir(cfigs.dir) if f.endswith(".png")])
    index.append(f"| **comparison** | [html](comparison/comparison.html) | "
                 f"[md](comparison/comparison.md) | "
                 f"[pdf](comparison/comparison.pdf) | {nf} |")

    index += ["", "Sources: `data/_qc/` (raw layer outputs). Method: "
                  "`research_logs/2026-08-10-dataset-quality-assessment-methods-and-plan.md`. "
                  "Results narrative: `research_logs/2026-08-10-dataset-qc-results.md`.", ""]
    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(index))
    print(f"[pkg] index -> {os.path.join(OUT, 'README.md')}")


if __name__ == "__main__":
    main()

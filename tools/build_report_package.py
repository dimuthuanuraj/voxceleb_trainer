def jload(p, d=None):
    return json.load(open(p, encoding="utf-8")) if os.path.isfile(p) else d


BIAS = jload(os.path.join(QC, "bias_transfer", "bias.json"), {})
SHIFT = jload(os.path.join(QC, "bias_transfer", "shift.json"), {})

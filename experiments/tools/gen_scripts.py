def load_results():
    """Read every completed run's best validation EER."""
    out = {}
    for path in sorted(glob.glob(os.path.join(RESULTS_DIR, "*", "final.json"))):
        exp_id = os.path.basename(os.path.dirname(path))
        if exp_id.endswith("__smoke") or exp_id.endswith("__dev"):
            continue  # reduced-scale runs must never drive selection
        try:
            with open(path, encoding="utf-8") as fh:
                final = json.load(fh)
            man_path = os.path.join(os.path.dirname(path), "manifest.json")
            with open(man_path, encoding="utf-8") as fh:
                man = json.load(fh)
        except Exception:
            continue
        if not final.get("best"):
            continue
        out[exp_id] = {
            "eer": final["best"]["val_eer"],
            "epoch": final["best"]["epoch"],
            "arch": man["experiment"]["architecture"],
            "loss": man["experiment"]["loss"],
            "condition": man["experiment"]["condition"],
            "stage": man["experiment"]["stage"],
        }
    return out


def rank_architectures(results, top=2):
    """Rank backbones by mean validation EER across the two languages.

    A backbone that wins on one language and collapses on the other is not a
    candidate for the later stages, so the mean is taken only over
    architectures that produced a result in BOTH conditions, and ties are broken
    by the worse of the two -- the later stages should carry forward the
    architecture that is reliably good, not the one with the single best cell.
    """
    per_arch = {}
    for r in results.values():
        if r["stage"] != "A":
            continue
        per_arch.setdefault(r["arch"], {})[r["condition"]] = r["eer"]
    complete = {a: v for a, v in per_arch.items() if {"si", "ta"} <= set(v)}
    if not complete:
        raise SystemExit(
            "no Stage A results with both si and ta yet -- run Stage A first "
            "(python experiments/tools/run_queue.py --stage A)"
        )
    ranked = sorted(
        complete.items(),
        key=lambda kv: (sum(kv[1].values()) / len(kv[1]), max(kv[1].values())),
    )
    return [a for a, _ in ranked[:top]], {
        a: {"mean_eer": round(sum(v.values()) / len(v), 4), "per_condition": v}
        for a, v in ranked
    }


def rank_pairs(results, top=2):
    """Best (architecture, loss) pairs by mean validation EER over si and ta."""
    per_pair = {}
    for r in results.values():
        if r["stage"] not in ("A", "B"):
            continue
        per_pair.setdefault((r["arch"], r["loss"]), {})[r["condition"]] = r["eer"]
    complete = {p: v for p, v in per_pair.items() if {"si", "ta"} <= set(v)}
    if not complete:
        raise SystemExit("no completed (arch, loss) pairs covering both languages yet")
    ranked = sorted(complete.items(), key=lambda kv: sum(kv[1].values()) / len(kv[1]))
    return [p for p, _ in ranked[:top]], {
        f"{a}+{l}": {"mean_eer": round(sum(v.values()) / len(v), 4), "per_condition": v}
        for (a, l), v in ranked
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--stage", required=True,
                    choices=["A", "B", "C", "D", "E", "F", "G", "H", "M", "all"])
    ap.add_argument("--top", type=int, default=2,
                    help="how many winners to carry into a deferred stage")
    ap.add_argument("--seeds", default="123,7", help="extra seeds for Stage D")
    ap.add_argument("--conditions", default=None,
                    help="comma-separated conditions for stages E/F/G "
                         "(default: si,ta for F/G; en_matched for E)")
    ap.add_argument("--archs", default=None,
                    help="comma-separated architectures for Stage E "
                         "(default: all Stage A backbones)")
    ap.add_argument("--initial-model", default=None,
                    help="English checkpoint for Stage G's fine-tune techniques")
    ap.add_argument("--force", action="store_true", help="overwrite existing scripts")
    args = ap.parse_args()

    os.makedirs(SCRIPT_DIR, exist_ok=True)
    selection = {}

    if args.stage == "A":
        conds = tuple(args.conditions.split(",")) if args.conditions else ("si", "ta")
        exps = R.stage_a(conditions=conds)
        selection = {"conditions": list(conds)}
    elif args.stage == "B":
        results = load_results()
        top_archs, table = rank_architectures(results, args.top)
        selection = {"selected_architectures": top_archs, "ranking": table}
        print(f"[stage B] carrying forward: {', '.join(top_archs)}")
        exps = R.stage_b(top_archs)
    elif args.stage == "C":
        results = load_results()
        pairs, table = rank_pairs(results, args.top)
        selection = {"selected_pairs": [list(p) for p in pairs], "ranking": table}
        print(f"[stage C] carrying forward: {', '.join(f'{a}+{l}' for a, l in pairs)}")
        exps = R.stage_c(pairs)
    elif args.stage == "D":
        results = load_results()
        pairs, table = rank_pairs(results, args.top)
        seeds = tuple(int(s) for s in args.seeds.split(","))
        selection = {"selected_pairs": [list(p) for p in pairs], "seeds": list(seeds),
                     "ranking": table}
        print(f"[stage D] replicating {', '.join(f'{a}+{l}' for a, l in pairs)} "
              f"at seeds {seeds}")
        exps = R.stage_d(pairs, seeds=seeds)
    elif args.stage == "E":
        conds = tuple((args.conditions or "en_matched").split(","))
        archs = args.archs.split(",") if args.archs else None
        exps = R.stage_en(archs=archs, conditions=conds)
        selection = {"conditions": list(conds),
                     "note": "English reference: en_full validates the harness "
                             "against published VoxCeleb1-O numbers; en_matched "
                             "makes the cross-language ranking comparison valid"}
    elif args.stage == "F":
        conds = tuple((args.conditions or "si,ta").split(","))
        exps = R.stage_f(conditions=conds)
        selection = {"conditions": list(conds),
                     "frontends": {k: v.get("note") for k, v in R.FRONTENDS.items()},
                     "reused_from_stage_A": [k for k, v in R.FRONTENDS.items()
                                             if v.get("reuse_stage_a")]}
    elif args.stage == "H":
        conds = tuple((args.conditions or "si,ta").split(","))
        exps = R.stage_h(conditions=conds)
        selection = {"conditions": list(conds),
                     "hybrids": {k: v["note"] for k, v in R.HYBRIDS.items()},
                     "compare_against": ["Stage A ecapa1024 (log-mel + ECAPA)",
                                         "Stage F ssl_wavlm_lw (WavLM + pooling head)"]}
    elif args.stage == "G":
        results = load_results()
        try:
            pairs, table = rank_pairs(results, 1)
            arch, loss = pairs[0]
        except SystemExit:
            arch, loss = "ecapa1024", R.STAGE_A_LOSS
            table = {"note": "no completed runs yet; defaulted to ecapa1024"}
        conds = tuple((args.conditions or "si,ta,combined").split(","))
        exps = R.stage_g(arch, loss, conditions=conds,
                         initial_model=args.initial_model)
        skipped = [t for t, v in R.TECHNIQUES.items()
                   if "initial_model" in v.get("requires", []) and not args.initial_model]
        selection = {"architecture": arch, "loss": loss, "conditions": list(conds),
                     "ranking": table,
                     "skipped_needing_initial_model": skipped}
        if skipped:
            print(f"[stage G] skipped (need --initial-model): {', '.join(skipped)}")
    elif args.stage == "M":
        results = load_results()
        pairs, table = rank_pairs(results, 1)
        arch, loss = pairs[0]
        if loss not in ("aamsoftmax", "amsoftmax"):
            print(f"[stage M] best loss {loss!r} has no margin; sweeping aamsoftmax "
                  f"on {arch} instead")
            loss = "aamsoftmax"
        selection = {"architecture": arch, "loss": loss, "ranking": table}
        exps = []
        for cond in ("si", "ta", "combined"):
            exps += R.stage_margin(arch, loss, cond)
    else:
        exps = R.stage_a()

    written = []
    for exp in exps:
        path = os.path.join(SCRIPT_DIR, f"{exp.exp_id}.py")
        if os.path.exists(path) and not args.force:
            print(f"  exists, skipping: {os.path.basename(path)} (use --force)")
            continue
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(render(exp))
        os.chmod(path, 0o755)
        written.append(exp.exp_id)
        print(f"  wrote {os.path.relpath(path, REPO_ROOT)}")

    # MERGE, don't overwrite. A stage can legitimately be generated in several
    # invocations -- Stage E is built as "7 backbones on en_matched" plus
    # "ecapa1024 on en_full", which are two different questions. Overwriting
    # would leave the manifest claiming 1 experiment while 8 scripts sit on
    # disk, and the manifest is the audit record the whole design leans on.
    man_path = os.path.join(SCRIPT_DIR, f"stage_{args.stage}_manifest.json")
    prior = {}
    if os.path.isfile(man_path):
        try:
            with open(man_path, encoding="utf-8") as fh:
                old = json.load(fh)
            prior = {e["exp_id"]: e for e in old.get("experiments", [])}
            prior_sel = old.get("selection_history", [])
            if old.get("selection"):
                prior_sel = prior_sel + [old["selection"]]
        except Exception:
            prior_sel = []
    else:
        prior_sel = []

    merged = dict(prior)
    for e in exps:
        d = e.describe()
        merged[d["exp_id"]] = d

    # Scripts that exist on disk but appear in no manifest entry would be
    # invisible to the record; surface them rather than let them sit unrecorded.
    on_disk = {os.path.splitext(os.path.basename(p))[0]
               for p in glob.glob(os.path.join(SCRIPT_DIR, f"{args.stage}_*.py"))}
    orphans = sorted(on_disk - set(merged))

    manifest = {
        "stage": args.stage,
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "n_experiments": len(merged),
        "experiments": [merged[k] for k in sorted(merged)],
        "selection": selection,
        "selection_history": prior_sel,
        "scripts_on_disk_not_in_manifest": orphans,
    }
    with open(man_path, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, default=str)
    if orphans:
        print(f"  NOTE: {len(orphans)} script(s) on disk are not described by "
              f"this stage's manifest: {', '.join(orphans[:4])}"
              f"{' ...' if len(orphans) > 4 else ''}")

    print(f"\n{len(written)} script(s) written, {len(exps)} in stage {args.stage}")
    print(f"manifest -> {os.path.relpath(man_path, REPO_ROOT)}")


if __name__ == "__main__":
    main()
